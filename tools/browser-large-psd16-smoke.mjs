import { createBrowserHighDepthFixture } from './browser-high-depth-fixtures.mjs';
import { createBrowserRendererHeapSampler } from './browser-renderer-heap-sampler.mjs';
import { createBrowserOperationTimeline } from './browser-operation-timeline.mjs';
import { writeBrowserOperationArtifact } from './browser-operation-artifact.mjs';
import { instrumentBrowserKernelSource } from './browser-inpaint-mid-kernel-smoke.mjs';
import { inspectNativeSelectedPixelChanges } from './browser-native-selection-integrity.mjs';

// Production file:// integration without exposing private editor state.
// Generated by ZeTer, NOT an independently Adobe Photoshop-authored golden.
// Memory figures are sampled CDP observations, NOT instantaneous/Worker peaks.
export async function verifyLargeBrowserPsd16Worker(client, {
  evaluate, waitFor, assert, browserClient = null, fixtureKey = 'rgb16large',
  testCancellation = false,
} = {}) {
  const fixture=createBrowserHighDepthFixture(fixtureKey);
  if (!fixture.large || !['rgb16large','rgb32psblarge'].includes(fixtureKey)) {
    throw new TypeError('Unsupported large native browser fixture');
  }
  const format=fixture.version===2?'PSB32':'PSD16';
  const rawBytes=fixture.width*fixture.height*fixture.channels*(fixture.bitsPerChannel/8);
  assert(rawBytes>8*1024*1024 && rawBytes<48*1024*1024,
    'Large native source must exceed v2 threshold but fit bounded native budget');
  const metadata={
    filename:fixture.filename,width:fixture.width,height:fixture.height,
    defectX:fixture.defectX,defectY:fixture.defectY,channels:fixture.channels,
    bitsPerChannel:fixture.bitsPerChannel,
  };
  const sampler=createBrowserRendererHeapSampler(client,{processClient:browserClient});
  const operation=createBrowserOperationTimeline({
    operationId:'stage003-'+format.toLowerCase()+(testCancellation?'-with-cancelled-retry':''),
    fixture:fixture.filename,format,
  });
  await sampler.start();
  operation.mark('source-selected');
  let samplerStopped=false;
  try {
  const importStart=Date.now();
  await evaluate(client,'window.__stage003LargeParts=[];window.__stage003LargeMeta='+JSON.stringify(metadata)+';true');
  // Chunk CDP evaluate payloads to avoid multi-megabyte WebSocket frames.
  const base64=Buffer.from(fixture.bytes).toString('base64');
  for(let offset=0;offset<base64.length;offset+=192*1024) {
    const piece=base64.slice(offset,offset+192*1024);
    await evaluate(client,'(() => {const binary=atob('+JSON.stringify(piece)+
      ');window.__stage003LargeParts.push(Uint8Array.from(binary,ch=>ch.charCodeAt(0)));return true;})()');
  }
  function dispatchFile() {
    const input=document.querySelector('#fileInput'),transfer=new DataTransfer();
    const parts=window.__stage003LargeParts;
    const bytes=parts.reduce((sum,part)=>sum+part.byteLength,0);
    transfer.items.add(new File(parts,window.__stage003LargeMeta.filename,{type:'image/vnd.adobe.photoshop'}));
    input.files=transfer.files;
    const receivedName=input.files[0]?.name;
    delete window.__stage003LargeParts;
    const confirm=window.confirm;
    window.confirm=()=>true;
    try { input.dispatchEvent(new Event('change',{bubbles:true})); }
    finally { window.confirm=confirm; }
    return {name:receivedName,bytes};
  }
  const dispatched=await evaluate(client,'('+dispatchFile.toString()+')()');
  assert(dispatched.name===fixture.filename && dispatched.bytes===fixture.bytes.length,
    'PSD/PSB UI input must receive full large file',JSON.stringify(dispatched));
  operation.mark('import-input-dispatched');

  function imported() {
    const f=window.__stage003LargeMeta;
    const canvas=document.querySelector('#editorCanvas');
    return canvas.width===f.width && canvas.height===f.height
      && document.querySelectorAll('.layer-row').length===1
      && document.querySelector('#statusText')?.textContent?.startsWith('PSD/PSB импортирован');
  }
  function beforePixel() {
    const f=window.__stage003LargeMeta;
    const pixel=document.querySelector('#editorCanvas').getContext('2d')
      .getImageData(f.defectX,f.defectY,1,1).data;
    return pixel[0]>100 && pixel[0]>pixel[1]*2;
  }
  await waitFor('large PSD/PSB browser import',()=>evaluate(client,'('+imported.toString()+')()'),45_000);
  await waitFor('large PSD/PSB defect preview',()=>evaluate(client,'('+beforePixel.toString()+')()'),30_000);
  operation.mark('import-preview-ready');
  await sampler.snapshot('after-large-import-preview');
  const importAndPreviewMs=Date.now()-importStart;

  async function readNativeFromSaveProject() {
    const f=window.__stage003LargeMeta;
    let blob=null;
    const original=URL.createObjectURL;
    URL.createObjectURL=function(value,...args) {
      if(value instanceof Blob && value.type==='application/json')blob=value;
      return original.call(URL,value,...args);
    };
    try {
      document.querySelector('.menu-button[data-menu="file"]').click();
      const save=[...document.querySelectorAll('#menuPopover .menu-item')].find(
        item=>item.querySelector('span')?.textContent?.startsWith('Сохранить проект'));
      if(!save || save.disabled)return {error:'Save Project menu unavailable'};
      save.click();
      if(!blob)return {error:'Save Project did not produce a JSON Blob'};
      const project=JSON.parse(await blob.text());
      const source=project.layers.find(layer=>layer.name==='Stage 003 native layer')?.highDepthSource;
      if(!source)return {error:'Imported layer lost native precision'};
      // Compare EVERY serialized native tile payload. A sampled RGBA preview
      // or a few Float32 values cannot prove unchanged 16/32-bit words.
      const payloads=source.tiles.map(tile=>tile.dataUrl);
      // A native byte oracle, independent of the 8-bit canvas preview.
      const selectionQuality=window.__stage003LargeNativeBaselineSource &&
        window.__stage003LargeFrozenSelection
        ?inspectNativeSelectedPixelChanges(
          window.__stage003LargeNativeBaselineSource,source,
          window.__stage003LargeFrozenSelection):null;
      const same=expected=>expected?.length===payloads.length &&
        payloads.every((value,index)=>value===expected[index]);
      const exactPayloadMatchesBaseline=window.__stage003LargeNativeBaseline
        ?same(window.__stage003LargeNativeBaseline):null;
      const exactPayloadMatchesSuccess=window.__stage003LargeNativeSuccess
        ?same(window.__stage003LargeNativeSuccess):null;
      if(window.__stage003LargeCaptureBaseline) {
        window.__stage003LargeNativeBaseline=payloads;
        window.__stage003LargeNativeBaselineSource=source;
        delete window.__stage003LargeCaptureBaseline;
      }
      if(window.__stage003LargeCaptureSuccess) {
        window.__stage003LargeNativeSuccess=payloads;
        delete window.__stage003LargeCaptureSuccess;
      }
      function sample(x,y) {
        const tile=source.tiles.find(item=>x>=item.x&&y>=item.y&&
          x<item.x+item.width&&y<item.y+item.height);
        if(!tile)return null;
        const decoded=Uint8Array.from(atob(tile.dataUrl.split(',')[1]),c=>c.charCodeAt(0));
        const view=new DataView(decoded.buffer);
        const sampleBytes=f.bitsPerChannel/8;
        const offset=((y-tile.y)*tile.width+x-tile.x)*f.channels*sampleBytes;
        return Array.from({length:f.channels},(_,ch)=>f.bitsPerChannel===16
          ?view.getUint16(offset+ch*sampleBytes,true)
          :view.getFloat32(offset+ch*sampleBytes,true));
      }
      return {name:project.name,kind:source.kind,bits:source.bitsPerChannel,
        rawBytes:source.rawBytes,tiles:source.tiles.length,
        normal:sample(0,0),damaged:sample(f.defectX,f.defectY),
        exactPayloadMatchesBaseline,exactPayloadMatchesSuccess,selectionQuality};
    } finally { URL.createObjectURL=original; }
  }
  // The test-only oracle is injected only for this ephemeral evaluate scope.
  const readNativeExpression='(() => {\n'+inspectNativeSelectedPixelChanges.toString()+
    '\nreturn ('+readNativeFromSaveProject.toString()+')();\n})()';
  await evaluate(client,'window.__stage003LargeCaptureBaseline=true;true');
  const native=await evaluate(client,readNativeExpression);
  assert(native.kind==='zpe-pixel-buffer-source-v2' && native.bits===fixture.bitsPerChannel &&
      native.rawBytes===rawBytes && native.tiles>1 &&
      JSON.stringify(native.normal)===JSON.stringify(fixture.normal) &&
      JSON.stringify(native.damaged)===JSON.stringify(fixture.damaged),
    'Large browser PSD/PSB must persist exact native v2 tile samples',JSON.stringify(native));
  operation.mark('native-source-verified');

  function setupMarquee() {
    const f=window.__stage003LargeMeta;
    const zoom=document.querySelector('#zoomRange');
    zoom.value='50';zoom.dispatchEvent(new Event('input',{bubbles:true}));
    document.querySelector('[data-tool="marquee"]').click();
    const type=document.querySelector('#selectionType');
    type.value='rect';type.dispatchEvent(new Event('change',{bubbles:true}));
    document.querySelector('#canvasShell').scrollIntoView({block:'center',inline:'center'});
    const viewport=document.querySelector('#stageViewport');
    viewport.scrollLeft=(viewport.scrollWidth-viewport.clientWidth)/2;
    viewport.scrollTop=(viewport.scrollHeight-viewport.clientHeight)/2;
    const canvas=document.querySelector('#editorCanvas'),rect=canvas.getBoundingClientRect();
    const point=(x,y)=>({x:rect.left+rect.width*x/f.width,
      y:rect.top+rect.height*y/f.height});
    const center=point(f.defectX,f.defectY);
    const start=point(f.defectX-12,f.defectY-12);
    const end=point(f.defectX+12,f.defectY+12);
    return {start,end,hit:document.elementFromPoint(center.x,center.y)?.id,
      center,width:rect.width,height:rect.height,
      within:start.x>0&&start.y>0&&end.x<innerWidth&&end.y<innerHeight};
  }
  const view=await evaluate(client,'('+setupMarquee.toString()+')()');
  assert(view.hit==='overlayCanvas' && view.within && view.width>200,
    'Large PSD/PSB marquee must be visible on real overlay',JSON.stringify(view));
  const mouse=(type,at,buttons)=>client.send('Input.dispatchMouseEvent',{
    type,x:at.x,y:at.y,button:'left',buttons,clickCount:1,
  });
  await mouse('mouseMoved',view.start,0);
  await mouse('mousePressed',view.start,1);
  await mouse('mouseMoved',view.end,1);
  await mouse('mouseReleased',view.end,0);
  operation.mark('selection-created');

  function observeWorker() {
    const post=Worker.prototype.postMessage;
    window.__stage003LargeWorkerJobs=0;
    window.__stage003RestoreLargeWorkerPost=()=>{
      Worker.prototype.postMessage=post;
      delete window.__stage003RestoreLargeWorkerPost;
    };
    Worker.prototype.postMessage=function(value,...args) {
      if(value?.selectedIndices instanceof Uint32Array &&
          value?.source?.kind==='zpe-pixel-buffer-source-v2') {
        window.__stage003LargeWorkerJobs++;
        window.__stage003LargeFrozenSelection=Uint32Array.from(value.selectedIndices);
      }
      return post.call(this,value,...args);
    };
    return true;
  }
  await evaluate(client,'('+observeWorker.toString()+')()');
  const fillStart=Date.now();
  function fillFromMenu() {
    document.querySelector('.menu-button[data-menu="edit"]').click();
    const item=[...document.querySelectorAll('#menuPopover .menu-item')].find(
      value=>value.querySelector('span')?.textContent==='Контент-заливка выделения');
    const enabled=Boolean(item&&!item.disabled);
    if(enabled)item.click();
    return {enabled,status:document.querySelector('#statusText')?.textContent};
  }
  const invoked=await evaluate(client,'('+fillFromMenu.toString()+')()');
  assert(invoked.enabled,'Large PSD/PSB Content-Aware Fill must be enabled',JSON.stringify(invoked));
  operation.mark('fill-command-invoked');
  function filledPreview() {
    const f=window.__stage003LargeMeta;
    const pixel=document.querySelector('#editorCanvas').getContext('2d')
      .getImageData(f.defectX,f.defectY,1,1).data;
    return window.__stage003LargeWorkerJobs===1 && pixel[0]<150;
  }
  await waitFor('large PSD/PSB tiled Worker and preview',
    ()=>evaluate(client,'('+filledPreview.toString()+')()'),60_000);
  function result() {
    const f=window.__stage003LargeMeta;
    return {jobs:window.__stage003LargeWorkerJobs,
      status:document.querySelector('#statusText')?.textContent||'',
      history:[...document.querySelectorAll('#historyList .history-row')].map(row=>row.textContent),
      pixel:Array.from(document.querySelector('#editorCanvas').getContext('2d')
        .getImageData(f.defectX,f.defectY,1,1).data)};
  }
  const after=await evaluate(client,'('+result.toString()+')()');
  assert(after.jobs===1 && after.status.includes('tiled ') &&
      after.history.filter(x=>x.includes('Контент-заливка')).length===1,
    'Large tiled UI Worker edit must create exactly one History entry',JSON.stringify(after));
  operation.mark('preview-history-published');
  await evaluate(client,'window.__stage003LargeCaptureSuccess=true;true');
  const firstNativeEdit=await evaluate(client,readNativeExpression);
  assert(firstNativeEdit.selectionQuality?.changedSelectedPixels>0 &&
      firstNativeEdit.selectionQuality.changedOutsideSelectionPixels===0,
    'Completed browser Worker must change native words only inside frozen selection',
    JSON.stringify(firstNativeEdit.selectionQuality));
  await sampler.snapshot('after-large-worker-preview');
  const fillAndPreviewMs=Date.now()-fillStart;
  await evaluate(client,"document.querySelector('#undoBtn').click();true");
  await waitFor('large PSD/PSB Undo',()=>evaluate(client,'('+beforePixel.toString()+')()'),30_000);
  operation.mark('undo-complete');
  await evaluate(client,"document.querySelector('#redoBtn').click();true");
  await waitFor('large PSD/PSB Redo',()=>evaluate(client,'('+filledPreview.toString()+')()'),30_000);
  const firstRedoNative=await evaluate(client,readNativeExpression);
  assert(firstRedoNative.selectionQuality?.changedSelectedPixels===
      firstNativeEdit.selectionQuality.changedSelectedPixels &&
      firstRedoNative.exactPayloadMatchesBaseline===false &&
      firstRedoNative.exactPayloadMatchesSuccess===true,
    'Redo must preserve selected native pixel changes without affecting other words',
    JSON.stringify(firstRedoNative.selectionQuality));
  operation.mark('redo-complete');
  await sampler.snapshot('after-large-undo-redo');
  if(testCancellation) {
    // Undo restores the original high-depth source. The second real UI Fill
    // is terminated DURING the CPU-bound native kernel, not after a reply.
    await evaluate(client,"document.querySelector('#undoBtn').click();true");
    await waitFor('native pre-cancellation Undo',()=>evaluate(client,'('+beforePixel.toString()+')()'),30_000);
    const retryView=await evaluate(client,'('+setupMarquee.toString()+')()');
    assert(retryView.hit==='overlayCanvas' && retryView.within,
      'Cancellation preflight must restore a real overlay marquee',JSON.stringify(retryView));
    await mouse('mouseMoved',retryView.start,0);
    await mouse('mousePressed',retryView.start,1);
    await mouse('mouseMoved',retryView.end,1);
    await mouse('mouseReleased',retryView.end,0);
    const baselineHistory=await evaluate(client,'('+result.toString()+')()');
    const baselineFillEntries=baselineHistory.history.filter(x=>x.includes('Контент-заливка')).length;
    await evaluate(client,'window.__stage003LargeCaptureBaseline=true;true');
    const nativeBeforeCancel=await evaluate(client,readNativeExpression);
    assert(JSON.stringify(nativeBeforeCancel.normal)===JSON.stringify(native.normal) &&
      JSON.stringify(nativeBeforeCancel.damaged)===JSON.stringify(native.damaged),
      'Undo must restore exact original native PSD/PSB samples before cancellation',
      JSON.stringify(nativeBeforeCancel));

    function installRealNativeKernelProbe() {
      const supplier=window.__zpeTiledInpaintWorkerSource;
      if(typeof supplier!=='string')throw new Error('Native file:// Worker supplier unavailable');
      const injected=instrumentBrowserKernelSource(supplier,{minimumWidth:9});
      const createUrl=URL.createObjectURL;
      const post=Worker.prototype.postMessage;
      const terminate=Worker.prototype.terminate;
      window.__stage003LargeKernelProbe={
        injectedBlobs:0,dispatchedJobs:0,afterWriteProbes:0,
        completedReplies:0,terminations:0,lastWrite:null,
      };
      URL.createObjectURL=function(blob,...args) {
        if(blob instanceof Blob && blob.type==='text/javascript') {
          window.__stage003LargeKernelProbe.injectedBlobs++;
          return createUrl.call(URL,new Blob([injected],{type:'text/javascript'}),...args);
        }
        return createUrl.call(URL,blob,...args);
      };
      Worker.prototype.postMessage=function(job,...args) {
        if(job?.selectedIndices instanceof Uint32Array &&
            job?.source?.kind==='zpe-pixel-buffer-source-v2') {
          window.__stage003LargeKernelProbe.dispatchedJobs++;
          const worker=this;
          const observe=function(event) {
            const data=event.data;
            if(data?.probe==='zpe-test-native-kernel-write') {
              window.__stage003LargeKernelProbe.afterWriteProbes++;
              window.__stage003LargeKernelProbe.lastWrite={
                filled:data.filled,changedSample:data.changedSample,
              };
              worker.removeEventListener('message',observe);
            } else if(data?.ok===true && Number.isInteger(data?.id)) {
              window.__stage003LargeKernelProbe.completedReplies++;
            }
          };
          worker.addEventListener('message',observe);
        }
        return post.call(this,job,...args);
      };
      Worker.prototype.terminate=function(...args) {
        window.__stage003LargeKernelProbe.terminations++;
        return terminate.apply(this,args);
      };
      window.__stage003RestoreCancelProbe=()=>{
        URL.createObjectURL=createUrl;
        Worker.prototype.postMessage=post;
        Worker.prototype.terminate=terminate;
        delete window.__stage003RestoreCancelProbe;
      };
      return {installed:true};
    }
    const installed=await evaluate(client,'(() => {\n'+
      instrumentBrowserKernelSource.toString()+'\nreturn ('+
      installRealNativeKernelProbe.toString()+')();\n})()');
    assert(installed.installed,'Cannot instrument isolated native Worker Blob');
    const cancellationStarted=Date.now();
    const pending=await evaluate(client,'('+fillFromMenu.toString()+')()');
    assert(pending.enabled,'Native mid-kernel Content-Aware command must start',JSON.stringify(pending));
    operation.mark('cancel-fill-command-invoked');
    await waitFor('actual native CPU-kernel write before cancellation',()=>evaluate(client,
      'window.__stage003LargeKernelProbe?.afterWriteProbes===1 && '+
      'window.__stage003LargeWorkerJobs===2'),60_000);
    const observed=await evaluate(client,'window.__stage003LargeKernelProbe');
    assert(observed.injectedBlobs===1 && observed.dispatchedJobs===1 &&
      observed.lastWrite?.filled===1 &&
      Number.isFinite(observed.lastWrite?.changedSample) &&
      observed.completedReplies===0,
      'Cancellation must observe a real native kernel pixel write before any result reply',
      JSON.stringify(observed));
    operation.mark('cancel-kernel-write-observed');
    const probeAt=Date.now();
    // A real UI lock revokes the live worker owner. Polling terminates the
    // CPU-spinning worker before its instrumented 6s deadline.
    await evaluate(client,"document.querySelector('.layer-row.selected .layer-lock').click();true");
    await waitFor('native mid-kernel Worker terminated by UI lock',()=>evaluate(client,
      'window.__stage003LargeKernelProbe?.terminations>=1'),15_000);
    operation.mark('cancel-owner-revoked');
    const stopped=await evaluate(client,'window.__stage003LargeKernelProbe');
    assert(stopped.completedReplies===0 && Date.now()-probeAt<5000,
      'Native kernel must terminate before CPU stall can finish',JSON.stringify(stopped));
    const cancelled=await evaluate(client,'('+result.toString()+')()');
    // The lock itself creates a History branch and may prune an undone Fill;
    // cancellation must never ADD a Fill entry to that branch.
    assert(cancelled.jobs===2 && cancelled.pixel[0]>100 &&
      cancelled.history.filter(x=>x.includes('Контент-заливка')).length<=baselineFillEntries,
      'Cancelled native kernel must not repaint or publish History',JSON.stringify(cancelled));
    const nativeAfter=await evaluate(client,readNativeExpression);
    assert(nativeAfter.exactPayloadMatchesBaseline===true &&
      nativeAfter.selectionQuality?.changedSelectedPixels===0,
      'Cancellation must preserve every original native tile byte',
      JSON.stringify({before:nativeBeforeCancel,after:nativeAfter}));
    operation.mark('cancel-native-verified');
    await sampler.snapshot('after-large-mid-kernel-cancel');
    console.log('Stage 003 '+format+' actual mid-kernel cancel:',JSON.stringify({
      observed,stopped,cancellationLatencyMs:Date.now()-cancellationStarted,
      terminateAfterObservedKernelWriteMs:Date.now()-probeAt,
      unchangedNativeTileBytes:true,
      note:'Real kernel write observed before terminate; CPU stall is test-only, not worker peak RSS',
    }));

    // Restore the unmodified production Worker source before retrying.
    await evaluate(client,'window.__stage003RestoreCancelProbe?.();true');
    await evaluate(client,"document.querySelector('.layer-row.selected .layer-lock').click();true");
    const restored=await evaluate(client,'('+fillFromMenu.toString()+')()');
    assert(restored.enabled,'Native Worker must accept a new UI Fill after unlock',JSON.stringify(restored));
    operation.mark('retry-fill-command-invoked');
    function retryFilledPreview() {
      const f=window.__stage003LargeMeta;
      const pixel=document.querySelector('#editorCanvas').getContext('2d')
        .getImageData(f.defectX,f.defectY,1,1).data;
      return window.__stage003LargeWorkerJobs===3 && pixel[0]<150;
    }
    await waitFor('native successor Worker recovered preview',()=>evaluate(client,
      '('+retryFilledPreview.toString()+')()'),60_000);
    const recovered=await evaluate(client,'('+result.toString()+')()');
    assert(recovered.jobs===3 &&
      recovered.history.filter(x=>x.includes('Контент-заливка')).length===1,
      'Recovered Worker must publish exactly one new Fill History entry',
      JSON.stringify(recovered));
    operation.mark('retry-preview-history-published');
    await evaluate(client,'window.__stage003LargeCaptureSuccess=true;true');
    const nativeSuccess=await evaluate(client,readNativeExpression);
    assert(nativeSuccess.exactPayloadMatchesBaseline===false &&
      nativeSuccess.selectionQuality?.changedSelectedPixels>0 &&
      JSON.stringify(nativeSuccess.damaged)!==JSON.stringify(native.damaged),
      'Recovered Fill must change real native high-depth words',JSON.stringify(nativeSuccess));
    await evaluate(client,"document.querySelector('#undoBtn').click();true");
    await waitFor('native retry Undo',()=>evaluate(client,'('+beforePixel.toString()+')()'),30_000);
    const undoNative=await evaluate(client,readNativeExpression);
    assert(undoNative.exactPayloadMatchesBaseline===true &&
      undoNative.selectionQuality?.changedSelectedPixels===0,
      'Undo must restore all original native little-endian tile words',JSON.stringify(undoNative));
    operation.mark('retry-undo-native-verified');
    await evaluate(client,"document.querySelector('#redoBtn').click();true");
    await waitFor('native retry Redo',()=>evaluate(client,
      '('+retryFilledPreview.toString()+')()'),30_000);
    const redoNative=await evaluate(client,readNativeExpression);
    assert(redoNative.exactPayloadMatchesSuccess===true &&
      redoNative.exactPayloadMatchesBaseline===false &&
      redoNative.selectionQuality?.changedSelectedPixels===
        nativeSuccess.selectionQuality.changedSelectedPixels,
      'Redo must restore exact native successor tile words',JSON.stringify(redoNative));
    operation.mark('retry-redo-native-verified');
    await sampler.snapshot('after-large-mid-kernel-recovered-redo');
    console.log('Stage 003 '+format+' native kernel recovery:',JSON.stringify({
      workerJobs:recovered.jobs,historyFillEntries:1,
      recoveredChangedNativeBytes:true,undoExactNativeBytes:true,redoExactNativeBytes:true,
    }));
  }
  const memory=await sampler.stop();
  samplerStopped=true;
  const operationProfile=operation.finish({
    outcome:testCancellation?'completed-with-cancelled-retry':'completed',
    memoryReport:memory,
  });
  const artifactPath=await writeBrowserOperationArtifact(operationProfile);
  if(artifactPath)console.log('Stage 003 browser operation JSON artifact:',artifactPath);
  await evaluate(client,'window.__stage003RestoreCancelProbe?.();window.__stage003RestoreLargeWorkerPost?.();delete window.__stage003LargeMeta;delete window.__stage003LargeNativeBaseline;delete window.__stage003LargeNativeSuccess;delete window.__stage003LargeKernelProbe;delete window.__stage003LargeNativeBaselineSource;delete window.__stage003LargeFrozenSelection;true');
  console.log('Stage 003 large file:// '+format+' Worker regression:',JSON.stringify({
    fixture:fixture.filename,source:'ZeTer-generated, NOT Adobe Photoshop-authored',
    rawBytes,tiles:native.tiles,workerJobs:after.jobs,importAndPreviewMs,fillAndPreviewMs,
    operationProfile,
    memory:{type:'informational CDP sampled, NOT memory peak',...memory},
  }));
  } finally {
    // Keep the Node process terminable even if a browser assertion rejects.
    // The sampler owns an interval; previous failures left it running until
    // GitHub Actions hit its 10-minute job timeout.
    if(!samplerStopped) await sampler.stop().catch(()=>{});
    await evaluate(client,'window.__stage003RestoreCancelProbe?.();window.__stage003RestoreLargeWorkerPost?.();delete window.__stage003LargeMeta;delete window.__stage003LargeNativeBaseline;delete window.__stage003LargeNativeSuccess;delete window.__stage003LargeKernelProbe;delete window.__stage003LargeNativeBaselineSource;delete window.__stage003LargeFrozenSelection;true')
      .catch(()=>{});
  }
}
