import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// Standalone classic Worker code: no module imports, fetch(), importScripts()
// or server are required. A parent file:// page loads the generated supplier
// as a normal script and makes a same-origin Blob Worker from its source text.
const root = resolve(import.meta.dirname, '..');
const dependencies = [
  'src/core/io.js',
  'src/core/inpaint.js',
  'src/core/pixel-buffer.js',
  'src/core/tiled-inpaint-worker-protocol.js',
];

function stripModules(source, filename) {
  const stripped = source
    .replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^\s*import\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^\s*export\s+(?=(?:async\s+)?function\b|class\b|const\b|let\b|var\b)/gm, '');
  if (/^\s*(?:import|export)\b/m.test(stripped)) {
    throw new Error('Unsupported ESM syntax in ' + filename);
  }
  return stripped.trim();
}

const chunks = [];
for (const file of dependencies) {
  chunks.push('// ---- ' + file + ' ----\n' + stripModules(await readFile(resolve(root, file), 'utf8'), file));
}
const entrypoint = `
self.addEventListener('message', event => {
  const job = event.data;
  const id = Number.isSafeInteger(job?.id) ? job.id : null;
  try {
    self.postMessage({ id, ok:true, result:runTiledInpaintWorkerJob(job) });
  } catch (error) {
    self.postMessage({
      id, ok:false, error:{
        name:String(error?.name || 'Error'),
        message:String(error?.message || error),
      },
    });
  }
});
self.postMessage({ ready:true });`;
const workerSource = [
  '/* ZeTer tiled Content-Aware Worker. Generated; do not edit. */',
  '(function(){',
  "'use strict';",
  ...chunks,
  entrypoint,
  '})();',
  '',
].join('\n\n');
const output = [
  '/* Generated by tools/build-tiled-inpaint-worker.mjs. Do not edit. */',
  '(function(){',
  "'use strict';",
  "Object.defineProperty(globalThis, '__zpeTiledInpaintWorkerSource', {",
  '  configurable:true, value:' + JSON.stringify(workerSource),
  '});',
  '})();',
  '',
].join('\n');
const outputPath = resolve(root, 'src/core/tiled-inpaint-worker-source.js');
if (process.argv.includes('--check')) {
  const actual = await readFile(outputPath, 'utf8');
  if (actual !== output) throw new Error('Generated tiled Worker source is stale; run npm run build');
} else {
  await writeFile(outputPath, output, 'utf8');
}
